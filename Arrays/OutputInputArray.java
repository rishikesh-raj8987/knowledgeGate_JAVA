package Arrays;

public class OutputInputArray {
    public static void main(String[] args) {
        int[] arr =  {45,-5,89,7,-14};
        for(int i=0;i<=4;i++){
            System.out.println(arr[i]+" ");
        }
        int j = 0;
        while(j<=4){
            System.out.print(arr[j]+" ");
            j++;
        }
    }
}
